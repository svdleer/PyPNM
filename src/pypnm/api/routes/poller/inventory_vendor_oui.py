def vendor_for_mac(mac: str) -> str | None:
    """Return the canonical vendor for a normalized or compact MAC address."""
    compact = "".join(character for character in str(mac or "").lower() if character in "0123456789abcdef")
    if len(compact) != 12:
        return None
    oui = ":".join(compact[index : index + 2] for index in range(0, 6, 2))
    return VENDOR_BY_OUI.get(oui)
